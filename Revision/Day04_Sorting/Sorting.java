package Revision.Day04_Sorting;

import java.util.Arrays;

public class Sorting {

    public static void main(String[] arg){

        int arr[]={20,50,30,10,40};
        Arrays.sort(arr);

        for(int i=0; i<arr.length;i++){
            System.out.print(arr[i]+" ");
        }

        // bubble sort



    }
}
